    public static string Greeting(string owner)
    {
        int h = DateTime.Now.Hour;
        if (h < 5) return $"Още ли не спиш, {owner}?";
        if (h < 11) return $"Добро утро, {owner}!";
        if (h < 18) return $"Добър ден, {owner}!";
        return $"Добър вечер, {owner}!";
    }

