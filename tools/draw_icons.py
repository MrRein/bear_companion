def ring(cx, cy, r0, r1, skip):
    """Пиксели на пръстен (за ↻ и часовника), без ъглите в skip (градуси)."""
    import math
    pts = []
    for y in range(12):
        for x in range(12):
            d = math.hypot(x + 0.5 - cx, y + 0.5 - cy)
            if r0 <= d <= r1:
                a = math.degrees(math.atan2(y + 0.5 - cy, x + 0.5 - cx)) % 360
                if not any(a0 <= a <= a1 for a0, a1 in skip):
                    pts.append((x, y))
    return pts


def toned(pts, hi, mid, lo, cx, cy):
    """Тон по посоката: горе вляво – светло, долу вдясно – тъмно."""
    out = {}
    for x, y in pts:
        s = (x + 0.5 - cx) + (y + 0.5 - cy)
        out[(x, y)] = hi if s < -3 else lo if s > 3 else mid
    return out


def reroll():
    # ↻ – пръстен с отвор горе вдясно и стрелка.
    px = toned(ring(6, 6, 2.6, 4.6, [(285, 345)]), "G", "g", "4", 6, 6)
    for x, y in ((8, 0), (9, 1), (10, 1), (9, 2), (10, 2), (8, 3), (9, 3), (10, 3), (11, 3)):
        px[(x, y)] = "g"
    return px


def history():
    # Часовник с назад-стрелка вляво.
    px = {}
    for x, y in ring(6.5, 6.5, 0, 4.6, []):
        px[(x, y)] = "c"
    for x, y in ring(6.5, 6.5, 0, 3.6, []):
        px[(x, y)] = "W"
    for x, y in ((6, 3), (6, 4), (6, 5), (6, 6), (7, 6), (8, 6)):
        px[(x, y)] = "k"
    for x, y in ((1, 1), (1, 2), (2, 2), (0, 3), (1, 3), (2, 3), (3, 3)):
        px[(x, y)] = "g"
    return px


def render(spec):
    if callable(spec):
        cells = spec()
        over = {}
        outline = True
    else:
        cells = {(x, y): ch for y, row in enumerate(spec["rows"]) for x, ch in enumerate(row) if ch != "."}
        over = {(x, y): ch for y, row in enumerate(spec.get("over", [])) for x, ch in enumerate(row) if ch != "."}
        outline = spec.get("outline", True)
    img = Image.new("RGBA", (12, 12), (0, 0, 0, 0))
    for (x, y), ch in cells.items():
        img.putpixel((x, y), PAL[ch] + (255,))
    if outline:
        for y in range(12):
            for x in range(12):
                if (x, y) in cells:
                    continue
                if any((x + a, y + b) in cells and cells[(x + a, y + b)] != "k" for a, b in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                    img.putpixel((x, y), K + (255,))
    for (x, y), ch in over.items():
        img.putpixel((x, y), PAL[ch] + (255,))
    return img


